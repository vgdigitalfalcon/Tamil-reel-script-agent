#!/usr/bin/env bash
# Add (or replace) an employee login in SCRIPTFALCON_CRM_USERS_JSON inside .env.
# Usage: bash deploy/add-user.sh            (prompts for details)
set -euo pipefail
cd "$(dirname "$0")/.."
[ -f .env ] || cp .env.example .env

read -rp "Email: " email
read -rp "Display name: " name
read -rp "Role (employee/admin) [employee]: " role
role="${role:-employee}"
read -rsp "Password: " pass; echo

DOCKER="docker"; docker info >/dev/null 2>&1 || DOCKER="sudo docker"
# Password goes via the environment, not argv, so it never shows up in `ps`.
SF_PASS="$pass" DOCKER_CMD="$DOCKER" python3 - "$email" "$name" "$role" <<'PY'
import json, os, re, subprocess, sys
from pathlib import Path

email, name, role = sys.argv[1].strip().lower(), sys.argv[2].strip(), sys.argv[3].strip().lower()
password = os.environ["SF_PASS"]
if role not in ("employee", "admin"):
    sys.exit("Role must be 'employee' or 'admin'.")
if len(password) < 10:
    sys.exit("Use a password of at least 10 characters.")

# bcrypt hash compatible with PHP password_verify(), generated by the PHP image itself.
php = "echo password_hash(stream_get_contents(STDIN), PASSWORD_DEFAULT);"
pw_hash = subprocess.run(
    os.environ["DOCKER_CMD"].split() + ["run", "--rm", "-i", "php:8.3-cli", "php", "-r", php],
    input=password, capture_output=True, text=True, check=True,
).stdout.strip()

env = Path(".env")
lines = env.read_text(encoding="utf-8").splitlines()
users = []
for ln in lines:
    if ln.startswith("SCRIPTFALCON_CRM_USERS_JSON="):
        raw = ln.split("=", 1)[1].strip().strip("'")
        users = json.loads(raw) if raw else []
users = [u for u in users if u.get("email", "").lower() != email]
users.append({
    "email": email,
    "password_hash": pw_hash,
    "role": role,
    "user_id": ("admin_" if role == "admin" else "emp_") + re.sub(r"[^a-z0-9_-]", "_", email.split("@")[0]),
    "display_name": name or email,
})
# Single quotes stop Docker Compose from expanding the '$' characters in bcrypt hashes.
new_line = "SCRIPTFALCON_CRM_USERS_JSON='" + json.dumps(users, separators=(",", ":")) + "'"
lines = [ln for ln in lines if not ln.startswith("SCRIPTFALCON_CRM_USERS_JSON=")] + [new_line]
env.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Saved login for {email} ({role}). Total users: {len(users)}")
PY
echo "Apply with: docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d"
